import re
with open('test_wiring_output3.txt', 'r') as f:
    text = f.read()

fails = re.findall(r'======================================================================.*?FAIL:.*?----------------------------------------------------------------------.*?[\n]*', text, re.DOTALL)
errs = re.findall(r'======================================================================.*?ERROR:.*?----------------------------------------------------------------------.*?[\n]*', text, re.DOTALL)
for f in fails: print(f)
for e in errs: print(e)
